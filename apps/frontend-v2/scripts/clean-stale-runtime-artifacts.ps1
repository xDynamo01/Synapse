param(
    [string] $RepositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot "..\..\..")).Path,
    [switch] $WhatIfOnly
)

$ErrorActionPreference = "Stop"

$repoRootPath = (Resolve-Path -LiteralPath $RepositoryRoot).Path.TrimEnd('\')
$documentationPath = Join-Path $repoRootPath ".cache\synapse\legacy-runtime-docs\runtime-entrypoint-hygiene.md"

$staleRuntimeTargets = @(
    @{
        Path = Join-Path $repoRootPath "dist"
        Reason = "Obsolete root Electron build path. The governed frontend build lives at apps\frontend-v2\dist."
    },
    @{
        Path = Join-Path $repoRootPath "release"
        Reason = "Obsolete root release output. The governed frontend release output lives under apps\frontend-v2 when packaging is explicitly requested."
    },
    @{
        Path = Join-Path $repoRootPath "out"
        Reason = "Obsolete root packaged output. It can shadow the current frontend-v2 runtime during manual launches."
    },
    @{
        Path = Join-Path $repoRootPath "apps\frontend-v2\release"
        Reason = "Packaged installer/unpacked output is not the local runtime source of truth and must be regenerated when needed."
    },
    @{
        Path = Join-Path $repoRootPath "apps\frontend-v2\out"
        Reason = "Obsolete frontend packaged output. The local launcher uses apps\frontend-v2\dist."
    }
)

function Assert-WorkspaceTarget {
    param([string] $TargetPath)

    $parent = Split-Path -Parent $TargetPath
    if (-not (Test-Path -LiteralPath $parent)) {
        return $null
    }

    $resolvedParent = (Resolve-Path -LiteralPath $parent).Path.TrimEnd('\')
    if (-not ($resolvedParent -eq $repoRootPath -or $resolvedParent.StartsWith($repoRootPath + '\'))) {
        throw "Refusing to clean outside repository root: $TargetPath"
    }

    if (Test-Path -LiteralPath $TargetPath) {
        $resolvedTarget = (Resolve-Path -LiteralPath $TargetPath).Path.TrimEnd('\')
        if (-not ($resolvedTarget -eq $repoRootPath -or $resolvedTarget.StartsWith($repoRootPath + '\'))) {
            throw "Refusing to clean outside repository root: $resolvedTarget"
        }
        return $resolvedTarget
    }

    return $null
}

$now = (Get-Date).ToString("yyyy-MM-dd HH:mm:ss zzz")
$removedEntries = New-Object System.Collections.Generic.List[string]
$checkedEntries = New-Object System.Collections.Generic.List[string]

foreach ($target in $staleRuntimeTargets) {
    $targetPath = [string] $target.Path
    $resolvedTarget = Assert-WorkspaceTarget -TargetPath $targetPath
    if ($null -eq $resolvedTarget) {
        $checkedEntries.Add("- absent: " + $targetPath)
        continue
    }

    $item = Get-Item -LiteralPath $resolvedTarget -Force
    $entry = "- removed: " + $resolvedTarget + " - " + $target.Reason + " LastWriteTime=" + $item.LastWriteTime.ToString("o")
    $removedEntries.Add($entry)

    if (-not $WhatIfOnly) {
        Remove-Item -LiteralPath $resolvedTarget -Recurse -Force
    }
}

$docParent = Split-Path -Parent $documentationPath
if (-not (Test-Path -LiteralPath $docParent)) {
    New-Item -ItemType Directory -Path $docParent | Out-Null
}

if (-not (Test-Path -LiteralPath $documentationPath)) {
    $initialDocumentation = @(
        "# Runtime entrypoint hygiene",
        "",
        "The governed local runtime entrypoint is:",
        "",
        "- $repoRootPath\Synapse.exe",
        "- generated by apps/frontend-v2/scripts/build-root-launcher.ps1",
        "- launching apps/frontend-v2/dist/main/main/main.js",
        "",
        "The following generated locations are treated as stale runnable surfaces when",
        "they exist in the workspace root or as package output:",
        "",
        "- dist",
        "- release",
        "- out",
        "- apps/frontend-v2/release",
        "- apps/frontend-v2/out",
        "",
        "They are removed before frontend builds so a local run cannot accidentally",
        "open an obsolete Electron bundle. Historical versions remain documented here;",
        "user data under AppData and the backup workspace are not touched.",
        ""
    )
    Set-Content -LiteralPath $documentationPath -Value ($initialDocumentation -join [Environment]::NewLine) -Encoding UTF8
}

$summaryLines = New-Object System.Collections.Generic.List[string]
$summaryLines.Add("")
$summaryLines.Add("## Hygiene run - $now")
if ($WhatIfOnly) {
    $summaryLines.Add("")
    $summaryLines.Add("Mode: dry run.")
}
$summaryLines.Add("")
$summaryLines.Add("Checked targets:")
$checkedEntries | ForEach-Object { $summaryLines.Add($_) }
if ($removedEntries.Count -gt 0) {
    $summaryLines.Add("")
    $summaryLines.Add("Removed stale runnable artifacts:")
    $removedEntries | ForEach-Object { $summaryLines.Add($_) }
} else {
    $summaryLines.Add("")
    $summaryLines.Add("Removed stale runnable artifacts: none.")
}

Add-Content -LiteralPath $documentationPath -Value ($summaryLines -join [Environment]::NewLine) -Encoding UTF8

Write-Output "runtime_hygiene_document=$documentationPath"
Write-Output "stale_artifacts_removed=$($removedEntries.Count)"
